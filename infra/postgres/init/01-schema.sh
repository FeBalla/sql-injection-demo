#!/usr/bin/env bash
# Creates the demo schema with a least-privilege application role.
#
# Runs once, as the owner role (POSTGRES_USER), on first container start.
# The app role can read and change rows in `customers` but does not own it,
# so even a successful injection cannot drop or alter the table, or touch
# anything else. Seed rows are inserted by the API on startup.
#
# A second database (<POSTGRES_DB>_test) gets the same setup for pytest.
set -euo pipefail

psql -v ON_ERROR_STOP=1 --username "$POSTGRES_USER" --dbname postgres \
  -v app_user="$APP_DB_USER" -v app_password="$APP_DB_PASSWORD" -v test_db="${POSTGRES_DB}_test" <<'SQL'
CREATE ROLE :"app_user" LOGIN PASSWORD :'app_password';
CREATE DATABASE :"test_db";
REVOKE CONNECT ON DATABASE postgres FROM PUBLIC;
SQL

for db in "$POSTGRES_DB" "${POSTGRES_DB}_test"; do
  psql -v ON_ERROR_STOP=1 --username "$POSTGRES_USER" --dbname "$db" -v app_user="$APP_DB_USER" <<'SQL'
REVOKE ALL ON DATABASE :"DBNAME" FROM PUBLIC;
GRANT CONNECT ON DATABASE :"DBNAME" TO :"app_user";
REVOKE ALL ON SCHEMA public FROM PUBLIC;
GRANT USAGE ON SCHEMA public TO :"app_user";

CREATE TABLE public.customers (
  id      integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name    text NOT NULL,
  email   text NOT NULL,
  country text NOT NULL,
  plan    text NOT NULL
);

GRANT SELECT, INSERT, DELETE, TRUNCATE ON public.customers TO :"app_user";
-- UPDATE on the sequence lets reset restart ids with setval().
GRANT USAGE, SELECT, UPDATE ON SEQUENCE public.customers_id_seq TO :"app_user";
SQL
done
